"""Generate a downloadable booking confirmation from a real Duffel order."""
from __future__ import annotations

import io
from datetime import datetime
from typing import Any

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib import colors


def _first(value: Any, default: str = "—") -> str:
    if value is None or value == "":
        return default
    return str(value)


def _passenger_name(passenger: dict[str, Any]) -> str:
    name = " ".join(x for x in [passenger.get("given_name"), passenger.get("family_name")] if x)
    return name or _first(passenger.get("name"))


def _extract_ticket_numbers(documents: list[dict[str, Any]]) -> list[str]:
    numbers: list[str] = []
    for doc in documents or []:
        for key in ("ticket_number", "document_number", "number"):
            value = doc.get(key)
            if value and str(value) not in numbers:
                numbers.append(str(value))
    return numbers


def _extract_segments(order: dict[str, Any]) -> list[dict[str, Any]]:
    segments: list[dict[str, Any]] = []
    for sl in order.get("slices") or []:
        for seg in sl.get("segments") or []:
            segments.append(seg)
    return segments


def build_booking_pdf(order: dict[str, Any], transaction: dict[str, Any]) -> bytes:
    """Return a PDF based only on the provider order and stored transaction.

    This is a customer-facing booking confirmation/e-ticket receipt. The PNR is
    the airline booking reference returned by Duffel. If the airline exposes an
    electronic ticket/document number in Duffel's order, it is shown too.
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, rightMargin=16*mm, leftMargin=16*mm,
        topMargin=14*mm, bottomMargin=14*mm,
        title="Trust Trip MAS Flight Booking Confirmation",
        author="Trust Trip MAS",
    )
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallMuted", parent=styles["Normal"], fontSize=8.5, textColor=colors.HexColor("#555555"), leading=11))
    styles.add(ParagraphStyle(name="BookingCode", parent=styles["Normal"], fontName="Courier-Bold", fontSize=15, leading=18))
    styles.add(ParagraphStyle(name="Section", parent=styles["Heading2"], fontSize=12, leading=15, spaceBefore=10, spaceAfter=6))

    pnr = order.get("booking_reference") or transaction.get("booking_reference")
    order_id = order.get("id") or transaction.get("duffel_order_id")
    live_mode = bool(order.get("live_mode"))
    documents = order.get("documents") or []
    ticket_numbers = _extract_ticket_numbers(documents)

    story = [
        Paragraph("TRUST TRIP MAS", styles["Title"]),
        Paragraph("Flight Booking Confirmation", styles["Heading1"]),
        Paragraph("Issued from the confirmed supplier order. This document is generated by Trust Trip MAS from the provider booking record.", styles["SmallMuted"]),
        Spacer(1, 8),
        Table([
            [Paragraph("AIRLINE BOOKING REFERENCE (PNR)", styles["SmallMuted"]), Paragraph("SUPPLIER ORDER", styles["SmallMuted"])],
            [Paragraph(_first(pnr), styles["BookingCode"]), Paragraph(_first(order_id), styles["BookingCode"])],
        ], colWidths=[88*mm, 88*mm], style=TableStyle([
            ("BOX", (0,0), (-1,-1), 0.7, colors.HexColor("#B8C1CC")),
            ("INNERGRID", (0,0), (-1,-1), 0.4, colors.HexColor("#D7DCE2")),
            ("VALIGN", (0,0), (-1,-1), "TOP"), ("LEFTPADDING", (0,0), (-1,-1), 7), ("RIGHTPADDING", (0,0), (-1,-1), 7),
            ("TOPPADDING", (0,0), (-1,-1), 6), ("BOTTOMPADDING", (0,0), (-1,-1), 6),
        ])),
    ]

    if ticket_numbers:
        story += [Paragraph("Electronic ticket/document number", styles["Section"]), Paragraph(", ".join(ticket_numbers), styles["BookingCode"])]
    else:
        story += [Paragraph("Ticket document", styles["Section"]), Paragraph("The airline/provider did not expose an electronic ticket number in the order response. The PNR above is the authoritative booking reference returned for this reservation.", styles["SmallMuted"])]

    story += [Paragraph("Passenger(s)", styles["Section"])]
    passengers = order.get("passengers") or []
    if not passengers:
        try:
            import json
            passengers = json.loads(transaction.get("passenger_json") or "[]")
        except Exception:
            passengers = []
    passenger_rows = [["Name", "Type", "Date of birth"]]
    for p in passengers:
        passenger_rows.append([_passenger_name(p), _first(p.get("type")), _first(p.get("born_on"))])
    story.append(Table(passenger_rows, colWidths=[95*mm, 35*mm, 46*mm], repeatRows=1, style=TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#EEF2F6")), ("GRID", (0,0), (-1,-1), 0.5, colors.HexColor("#C9D0D8")),
        ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"), ("FONTSIZE", (0,0), (-1,-1), 8.5),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
    ])))

    story += [Paragraph("Itinerary", styles["Section"])]
    seg_rows = [["Flight", "From → To", "Departure", "Arrival", "Operating carrier"]]
    for seg in _extract_segments(order):
        origin = (seg.get("origin") or {}).get("iata_code") or (seg.get("origin") or {}).get("name") or "—"
        destination = (seg.get("destination") or {}).get("iata_code") or (seg.get("destination") or {}).get("name") or "—"
        carrier = (seg.get("operating_carrier") or {}).get("name") or (seg.get("marketing_carrier") or {}).get("name") or "—"
        flight_no = seg.get("marketing_carrier_flight_number") or seg.get("operating_carrier_flight_number") or "—"
        seg_rows.append([str(flight_no), f"{origin} → {destination}", _first(seg.get("departing_at")), _first(seg.get("arriving_at")), carrier])
    story.append(Table(seg_rows, colWidths=[25*mm, 39*mm, 43*mm, 43*mm, 32*mm], repeatRows=1, style=TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#EEF2F6")), ("GRID", (0,0), (-1,-1), 0.5, colors.HexColor("#C9D0D8")),
        ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"), ("FONTSIZE", (0,0), (-1,-1), 7.5),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
    ])))

    story += [Paragraph("Payment and booking status", styles["Section"]), Table([
        ["Supplier total", f"{_first(order.get('total_currency'))} {_first(order.get('total_amount'))}"],
        ["Customer payment", f"{_first(transaction.get('currency'), 'INR')} {_first(transaction.get('amount'))}"],
        ["Razorpay payment", _first(transaction.get("razorpay_payment_id"))],
        ["Environment", "LIVE" if live_mode else "TEST / SANDBOX"],
        ["Booked at", _first(order.get("created_at"))],
    ], colWidths=[55*mm, 127*mm], style=TableStyle([
        ("GRID", (0,0), (-1,-1), 0.5, colors.HexColor("#C9D0D8")), ("FONTNAME", (0,0), (0,-1), "Helvetica-Bold"),
        ("FONTSIZE", (0,0), (-1,-1), 8.5), ("VALIGN", (0,0), (-1,-1), "TOP"),
    ]))]

    story += [Spacer(1, 10), Paragraph(
        "Important: This PDF is a downloadable booking confirmation generated from the real supplier order. It is not a substitute for an airline-issued boarding pass. Check the airline's official site/app for check-in and boarding-pass issuance.",
        styles["SmallMuted"],
    )]
    doc.build(story)
    return buf.getvalue()
